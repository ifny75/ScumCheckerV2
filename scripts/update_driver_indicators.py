"""Refresh detection metadata only; never downloads driver binaries."""
import argparse
import hashlib
import json
import re
import urllib.request
from pathlib import Path

SOURCE = "https://www.loldrivers.io/api/drivers.json"
parser = argparse.ArgumentParser()
parser.add_argument("--source", type=Path, help="Use a saved upstream JSON snapshot")
args = parser.parse_args()
raw = args.source.read_bytes() if args.source else urllib.request.urlopen(SOURCE, timeout=60).read()
records = json.loads(raw)
hashes, names = {}, set()
for record in records:
    if record.get("Category") != "vulnerable driver" or str(record.get("Verified")).lower() != "true":
        continue
    tags = [str(tag).lower() for tag in record.get("Tags", [])]
    safe_names = [tag for tag in tags if re.fullmatch(r"[a-z0-9_. -]+\.sys", tag)]
    names.update(safe_names)
    for sample in record.get("KnownVulnerableSamples", []):
        sha = str(sample.get("SHA256", "")).lower()
        if re.fullmatch(r"[a-f0-9]{64}", sha):
            hashes[sha] = safe_names[0] if safe_names else record["Id"]
if len(hashes) < 100:
    raise ValueError("Refusing an unexpectedly small driver indicator snapshot")
root = Path(__file__).resolve().parent.parent
lines = ["// Generated by scripts/update_driver_indicators.py; detection metadata only.",
         "// Source: " + SOURCE, "// Upstream: magicsword-io/LOLDrivers, Apache-2.0; see notices/.",
         "// Source snapshot SHA-256: " + hashlib.sha256(raw).hexdigest(),
         "#pragma once", "namespace ns::driver_data {",
         "struct Sample { const wchar_t* sha256; const wchar_t* name; };",
         "inline constexpr Sample samples[] = {"]
lines += ['    {L"' + sha + '", L"' + name + '"},' for sha, name in sorted(hashes.items())]
lines += ["};", "inline constexpr const wchar_t* names[] = {"]
lines += ['    L"' + name + '",' for name in sorted(names)]
lines += ["};", "} // namespace ns::driver_data", ""]
(root / "scanner" / "VulnerableDriverData.h").write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {len(hashes)} verified vulnerable sample hashes and {len(names)} family names")
